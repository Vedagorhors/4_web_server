// импортируем mongoose
const mongoose = require("mongoose");
// В монгусе нет валидации, но для этого есть спецаильный пакет. установим его командой npm i validator и подключим в проекте
const validator = require("validator");

// описываем схему данных. Схема будет позволять монгузу валидировать наши данные, перед тем как отправлять в базу. На уровне базы никакой валидации в данном случае не описывается, то есть база не будет проверять какой документ мы добавили. Но при этом мы не хотим, чтобы поломанные данные попали внутрь нашей базы, поэтому на уровне приложения будем проверять, что данные правильные. Описываем схему:
const UserSchema = mongoose.Schema({
  // у нас будет одно интересующее нас поле title. Описываем его тип и говорим, что это поле обязательное. Если title будет не полноценная строка (то есть он может быть null, undefined...) с каким-то количеством символов, то mongoose не даст нам сохранить данные
  email: {
    type: String,
    required: true,
    unique: true,
    validate: {
      validator: validator.isEmail,
      message: "Invalid email",
    },
  },
  password: {
    type: String,
    required: true,
  },
});
// и дальше эту схему нужно превратить в модель, то есть Схема. - это описание самой структуры данных, какие валидаторы будут использоваться и так далее, а модель - это уже абстракция с которой мы будем работать, то есть модель нам будет позволять сохранять данные, доставать данные т.д. Передаем имя модели Note  и схему, на основе которой работает эта модель.
const User = mongoose.model("User", UserSchema);
// эту модель юзера нам нужно теперь использовать, для этого создадим контроллер users.controller.js

// Экспортируем созданную модель
module.exports = User;

