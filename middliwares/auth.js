// Нужно проверить, что пользователь залогинен перед тем, как пускать его на главную страницу, если он не залогинен, то отправлять логиниться. Чтобы реализовать этот функционал напишем свой собственный middleware
// Подключим модуль jwt.
const jwt = require("jsonwebtoken");
// подключим константу JWT_SECRET
const { JWT_SECRET } = require("../constants");

function auth(req, res, next) {
  // необходимо проверить JWT. Для начала достанем его, то есть получим поле token
  const token = req.cookies.token;

  try {
    // У JWT есть метод veryfy, в который передадим сам токен и тот ключ, который использовали, то есть JWT_SECRET
    const veryfyResult = jwt.verify(token, JWT_SECRET);

    // будем добавлять для всех последующих обработчиков информацию, а что это за пользователь, просто создаем в request новое поле user и складываем туда объект, в который записываем пока только емаил. Теперь дальнейшие обработчики, например, создание заметки, будут знать, что есть пользователь, который записан в объект request и у него есть такой емаил veryfyResult.email и что именно этот пользователь пришел к нам с запросом. Это нужно для того, чтобы мы смогли поправить наши обработчики и настроить работу с ролями.
    req.user = {
      email: veryfyResult.email,
    };

    next();
  } catch (e) {
    // если мы получили ошибку, значит токен неправильный и нам нужно отправить пользователя логиниться
    res.redirect("./login");
  }
  // на выходе получим либо ошибку либо расшифрованный токен. Для начала выведем в консоль
  //   console.log(veryfyResult);
  // В консоли видим расшифрованный json web token: { email: 'qwe@qwe.ru', iat: 1793609080, exp: 1796201080 }.
  // Если же мы в девтулз допишем что-то, например, 1 в начало значения кука, то метод verify бросает ошибку, а значит её нужно обрабатывать, для этого используем комбинацию try/catch, см. выше
  // чтобы обработка продолжилась, то есть чтобы выполнение кода не застревало внутри middware, а переходило дальше к контроллерам, нам необходимо вызвать функцию next
  //   next(); - уже не нужен, так как мы уже отправили пользователя на другую страницу res.redirect("./login");
}

module.exports = auth;
