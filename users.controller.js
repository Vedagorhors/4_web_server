// Контроллер для модели юзера
// импортируем модель юзера
const User = require("./models/User");
// подключим установленные пакеты шифрования пароля bcrypt и позже когда установим, подключаем jwt
const bcrypt = require("bcrypt");
const jwt = require("jsonwebtoken");
const { JWT_SECRET } = require("./constants");

// контроллер регистрации
async function addUser(email, password) {
  // создадим хэш нашего пароля зарегестрировашегося пользователя на нашем сайте. Будем использовать асинхронную версию хэширования, так как она не заставляет наш сервер ждать. В функцию hash передаем два аргумента, первый данные, которые мы хотим захэшировать, в данном случае это пароль, вторым аргументом добавим так называемую "соль" или количество раундов создания соли, то есть к хэшу пароля еще добавляется комбинация симовлов спереди или сзади, чтобы трудно было расшифровать мошеннику хакеру, добавим число 10, не больше 10, иначе будет тормозить. Пакет bcrypt создает эту соль, а мы здесь просто указываем количество раундов шифрования (создания соли) и чем это число больше тем больше bcrypt будет формировать соль и более надежным будет наш хэш, но и сложнее будет нашему серверу обрабатывать поток запросов на создание пользователей, поэтому рекомендует наставник задавать число 10, не больше 11.
  const passwordHash = await bcrypt.hash(password, 10);
  // создаем нового пользователя
  await User.create({ email, password: passwordHash });
}

// контроллер для login
async function loginUser(email, password) {
  // каким образом нам залогинить пользователя. Для начала нам нужно провести этап индентификации, а именно - у нас есть емаил и нужно проверить есть ли вообще пользователь с таким емаилом. Вызываем метод findOne и передаем в него фильтр емали, то есть будем фильтровать по емаилу, то есть нужно найти пользователя с таким емаилом.
  const user = await User.findOne({ email });

  // если пользователя нет с таким емаилом, то выводим ошибку
  if (!user) {
    throw new Error("User is not found");
  }
  // если пользователь есть, то проверяем, что его пароль действительно правильный, для этого в bcrypt есть готовая функция compare. В первый агрумент передаем пароль, который не захэширован, а вторым с чем хотим сравнить, с какими захэшированными данными, то есть с захэшированным паролем
  const isPasswordCorrect = await bcrypt.compare(password, user.password);

  // если пользователя передал неправильный пароль, то выводим ошибку
  if (!isPasswordCorrect) {
    throw new Error("Wrong password");
  }

  // вызываем метод sign  и в него передадим параметры - первый это что будем шифровать, то есть email. Сразу делаем объект { email }, чтобы если что могли бы еще добавить какие-то данные внутрь нашего jwt и передадим созданный секрет.
  return jwt.sign({ email }, JWT_SECRET, { expiresIn: "30d" });
}

// экспортируем этот контроллер
module.exports = { addUser, loginUser };
// теперь мы можем использовать функцию addUser и подключить обработчик на регистрацию

