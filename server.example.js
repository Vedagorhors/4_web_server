// devDependecies - это зависимости, которые нужны именно для разработки. Кстати по хорошему давайте перенесем запись "@types/yargs": "^17.0.4" из dependecies в devDependecies, потому что это внутренние типы дляработы и нужно хранить их здесь, а вот пакеты chalk и yargs нужны для того, чтобы наше приложение работало, поэтому храним их в dependecies
